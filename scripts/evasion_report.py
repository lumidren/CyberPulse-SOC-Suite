#!/usr/bin/env python3
"""
Run the evasion cases (scripts/evasion_cases.py) and document which tricks bypass which
rules (roadmap F29).

    python scripts/evasion_report.py           # write docs/EVASION.md
    python scripts/evasion_report.py --check   # exit 1 if the committed report is stale
"""

import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from scripts.evasion_cases import CASES  # noqa: E402
from soar.sigma_engine import SigmaEngine  # noqa: E402

REPORT = os.path.join(ROOT, "docs", "EVASION.md")


def results():
    engine = SigmaEngine()
    rows = []
    for case in CASES:
        hits = sorted(r.soar.get("soc_rule_id", r.id) for r in engine.match_all(case["event"]))
        rows.append({**case, "actual": "detected" if case["rule"] in hits else "bypass",
                     "caught_by_other": [h for h in hits if h != case["rule"]]})
    return rows


def render():
    rows = results()
    bypasses = [r for r in rows if r["actual"] == "bypass"]
    unseen = [r for r in bypasses if not r["caught_by_other"]]
    lines = [
        "# Evasion Tests",
        "",
        "> Generated by `python scripts/evasion_report.py` from `scripts/evasion_cases.py`.",
        "> Synthetic telemetry only: each case is a process or access record, nothing is executed.",
        "",
        f"**{len(bypasses)}/{len(rows)} variants bypass the rule they target; {len(unseen)} of those are not "
        "caught by any other rule either.** Every bypass below is a known, unfixed weakness, published so it",
        "can be fixed rather than discovered by an intruder.",
        "",
        "| Case | Rule | Technique | Trick | Result | Caught elsewhere |",
        "| :--- | :--- | :--- | :--- | :--- | :--- |",
    ]
    for r in rows:
        result = "detected" if r["actual"] == "detected" else "**BYPASS**"
        lines.append(f"| {r['id']} | {r['rule']} | {r['technique']} | {r['trick']} | {result} | "
                     f"{', '.join(r['caught_by_other']) or '-'} |")
    lines += ["", "## How each bypass could be closed", ""]
    lines += [f"- **{r['id']}** ({r['rule']}, {r['trick']}): {r['note']}" for r in bypasses]
    lines += ["", "Detected variants are kept as regression checks: they must keep matching.", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Evasion test report")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    body = render()
    if args.check:
        try:
            with open(REPORT, encoding="utf-8") as fh:
                sys.exit(0 if fh.read().replace("\r\n", "\n") == body else 1)
        except FileNotFoundError:
            sys.exit(1)
    with open(REPORT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body)
    print(f"wrote {os.path.relpath(REPORT, ROOT)}")


if __name__ == "__main__":
    main()
