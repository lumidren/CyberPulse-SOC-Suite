#!/usr/bin/env python3
"""
Threshold tuning against historical data (roadmap F14).

For every rule with a numeric threshold (a ``|gt``/``|gte``/``|lt``/``|lte`` field in a
single-event rule, or the condition of a correlation rule), replay a dataset at several
candidate thresholds and count how often the rule fires.

    python scripts/tune_thresholds.py                       # synthetic baseline -> docs/THRESHOLD_TUNING.md
    python scripts/tune_thresholds.py --check               # exit 1 if the committed report is stale
    python scripts/tune_thresholds.py --benign my.jsonl --malicious attacks.jsonl --print

``--benign`` / ``--malicious`` take JSON Lines files of events in the pipeline's event
format (export them from your SIEM). With your own data the report prints to stdout
and is never written into the repo, so real logs are not committed by accident.
The suggested threshold is the most sensitive candidate whose benign firings stay
within ``--fp-budget`` (default 0); it is a starting point for review, not a setting
to apply blindly.
"""

import argparse
import copy
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from scripts.validate_detections import BASELINE_COUNT, BASELINE_SEED  # noqa: E402
from simulator.benign_baseline import generate_baseline  # noqa: E402
from soar.sigma_correlation import CorrelationEngine, event_time  # noqa: E402
from soar.sigma_engine import SigmaEngine, SigmaRule  # noqa: E402

REPORT = os.path.join(ROOT, "docs", "THRESHOLD_TUNING.md")
THRESHOLD_OPS = ("gte", "gt", "lte", "lt")


def _candidates(current):
    base = {1, 2, 3, 5, 10, 15, 20, 30, 50, 100, 200}
    return sorted(base | {int(current)} | {max(1, int(current) // 2), int(current) * 2})


def field_thresholds(rule):
    """[(selection, field_spec, op, value)] for numeric threshold fields in a single-event rule."""
    found = []
    for sel_name, sel in rule.selections.items():
        if not isinstance(sel, dict):
            continue
        for spec, value in sel.items():
            ops = [op for op in spec.split("|")[1:] if op in THRESHOLD_OPS]
            if ops and isinstance(value, (int, float)) and not isinstance(value, bool):
                found.append((sel_name, spec, ops[0], value))
    return found


def sweep_field(rule, sel_name, spec, current, benign, malicious):
    rows = []
    for t in _candidates(current):
        doc = copy.deepcopy(rule.doc)
        doc["detection"][sel_name][spec] = t
        variant = SigmaRule(rule.path, doc, rule.soar)
        rows.append((t, sum(map(variant.matches, benign)), sum(map(variant.matches, malicious)) if malicious else None))
    return rows


def sweep_correlation(rule_id, current, benign, malicious):
    def fires(events, t):
        engine = CorrelationEngine()
        target = next(r for r in engine.rules if r.id == rule_id)
        target.threshold = t
        engine.rules = [target]
        return sum(len(engine.observe(e)) for e in sorted(events, key=event_time))

    return [(t, fires(benign, t), fires(malicious, t) if malicious else None) for t in _candidates(current)]


def suggest(rows, op, fp_budget):
    """Most sensitive threshold within the FP budget: lowest for gt/gte, highest for lt/lte."""
    if all(fp == 0 for _, fp, _ in rows):
        return None  # the data never reaches the rule, so it cannot inform the threshold
    ok = [t for t, fp, _ in rows if fp <= fp_budget]
    if not ok:
        return None
    return min(ok) if op in ("gt", "gte") else max(ok)


def analyse(benign, malicious, fp_budget):
    results = []
    for rule in SigmaEngine().rules:
        for sel_name, spec, op, value in field_thresholds(rule):
            rows = sweep_field(rule, sel_name, spec, value, benign, malicious)
            results.append({"rule": rule.soar.get("soc_rule_id", rule.id), "title": rule.title,
                            "parameter": f"{sel_name}.{spec}", "op": op, "current": value, "rows": rows,
                            "suggested": suggest(rows, op, fp_budget)})
    for corr in CorrelationEngine().rules:
        rows = sweep_correlation(corr.id, corr.threshold, benign, malicious)
        results.append({"rule": corr.soar.get("soc_rule_id", corr.id), "title": corr.title,
                        "parameter": f"correlation {corr.type} ({corr.timespan}s window)", "op": corr.op,
                        "current": corr.threshold, "rows": rows, "suggested": suggest(rows, corr.op, fp_budget)})
    return results


def render(results, source, fp_budget):
    lines = [
        "# Threshold Tuning",
        "",
        f"> Generated by `python scripts/tune_thresholds.py`. Data: {source}.",
        "",
        f"Firings per candidate threshold. *Suggested* is the most sensitive threshold with at most "
        f"{fp_budget} benign firing(s); review it before changing a rule.",
        "",
    ]
    for r in results:
        lines += [f"## {r['rule']}: {r['title']}", "",
                  f"Parameter `{r['parameter']}` ({r['op']}), current **{r['current']}**, "
                  f"suggested **{r['suggested'] if r['suggested'] is not None else 'none (no usable signal in this data)'}**.", ""]
        has_mal = any(m is not None for *_, m in r["rows"])
        lines += ["| Threshold | Benign firings |" + (" Malicious firings |" if has_mal else ""),
                  "| ---: | ---: |" + (" ---: |" if has_mal else "")]
        for t, fp, tp in r["rows"]:
            mark = " (current)" if t == r["current"] else ""
            lines.append(f"| {t}{mark} | {fp} |" + (f" {tp} |" if has_mal else ""))
        if all(fp == 0 for _, fp, _ in r["rows"]):
            lines += ["", "No benign event reaches this rule at any candidate threshold, so this data cannot tune it."]
        lines.append("")
    return "\n".join(lines)


def load_jsonl(path):
    with open(path, encoding="utf-8") as fh:
        return [json.loads(line) for line in fh if line.strip()]


def synthetic_report():
    benign = generate_baseline(BASELINE_COUNT, BASELINE_SEED)
    source = (f"synthetic benign baseline ({BASELINE_COUNT} events, seed {BASELINE_SEED}); no malicious set. "
              "The baseline's distributions were chosen by the rule author, so suggestions here reflect the "
              "generator, not real behaviour; no rule threshold was changed from this report")
    return render(analyse(benign, [], 0), source, 0)


def main():
    parser = argparse.ArgumentParser(description="Sweep rule thresholds over historical events")
    parser.add_argument("--benign", help="JSON Lines file of benign historical events")
    parser.add_argument("--malicious", help="JSON Lines file of known-malicious events")
    parser.add_argument("--fp-budget", type=int, default=0)
    parser.add_argument("--print", action="store_true", help="print instead of writing the report")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.benign or args.malicious:
        benign = load_jsonl(args.benign) if args.benign else []
        malicious = load_jsonl(args.malicious) if args.malicious else []
        source = f"{len(benign)} benign / {len(malicious)} malicious events supplied on the command line"
        print(render(analyse(benign, malicious, args.fp_budget), source, args.fp_budget))
        return
    body = synthetic_report()
    if args.check:
        try:
            with open(REPORT, encoding="utf-8") as fh:
                sys.exit(0 if fh.read().replace("\r\n", "\n") == body else 1)
        except FileNotFoundError:
            sys.exit(1)
    if args.print:
        print(body)
        return
    with open(REPORT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body)
    print(f"wrote {os.path.relpath(REPORT, ROOT)}")


if __name__ == "__main__":
    main()
