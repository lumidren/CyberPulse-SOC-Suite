sys.path.insert(0, ROOT)
os.environ.setdefault("CYBERPULSE_LAB_MODE", "true")  # the regression corpus uses the lab generators

from scripts.coverage_report import gaps  # noqa: E402
from scripts.evasion_report import results as evasion_results  # noqa: E402
