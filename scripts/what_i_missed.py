def shadowed_rules():
    """Positive samples whose own rule matched but another rule was reported as the top match."""
    soc_by_file = {os.path.basename(r.file): r.soar.get("soc_rule_id") for r in SigmaEngine().rules}
    rows = []
    for key, event, kind, owner in corpus():
        if kind != "positive":
            continue
        own = soc_by_file.get(owner)
        result = evaluate(event)
        if own in result["all"] and result["top"] != own:
            rows.append((key.split("::")[-1], own, result["top"]))
    return rows


def render():
    bypasses = [r for r in evasion_results() if r["actual"] == "bypass"]
    _, uncovered = gaps()
    shadowed = shadowed_rules()
    baseline, scored = baseline_build()
    negatives = scored["negative"]
    flagged_neg = sum(1 for *_, s in negatives if s["verdict"] in {"RARE", "NEVER_SEEN"})
    lines = [
        "# What I Missed",
        "",
        "> Generated by `python scripts/what_i_missed.py` from the evasion tests, gap report, regression corpus",
        "> and behavioural baseline, plus a hand-kept list of what has never been run for real.",
        "",
        "Detection engineering work is easy to oversell. This page is the opposite: every known miss in one place.",
        "",
        f"## 1. Bypasses I found in my own rules ({len(bypasses)})",
        "",
    ]
    lines += [f"- **{r['rule']}**: {r['trick']} ({r['technique']}). {r['note']}" for r in bypasses]
    lines += ["", "Details and the detected variants: [EVASION.md](EVASION.md).", "",
              f"## 2. Techniques with no rule ({len(uncovered)})", ""]
    lines += [f"- **{t}** {e['name']}: {e.get('blocker') or e['why']}" for t, e in sorted(uncovered.items())]
    lines += ["", "Source: [coverage/GAPS.md](coverage/GAPS.md).", "",
              f"## 3. Attacks reported under the wrong name ({len(shadowed)})", "",
              "The rule written for these attacks matches, but another rule ranks first (higher severity, or the same",
              "severity and a lower rule id), so the analyst sees a less specific title; the more specific rule is",
              "only listed in `also_matched`.", ""]
    lines += [f"- {name}: written for {own}, reported as {top}" for name, own, top in shadowed] or ["None."]
    lines += ["", "## 4. Signals that do not work yet", "",
              f"- Rare parent-child baseline: flags {flagged_neg}/{len(negatives)} benign near-miss samples as well as "
              f"the attacks, because the synthetic baseline has only {len(baseline.counts)} distinct pairs "
              "([BEHAVIORAL_BASELINE.md](BEHAVIORAL_BASELINE.md)).",
              "- Threshold tuning: no correlation rule receives any benign events from the synthetic baseline, so their "
              "thresholds are untuned ([THRESHOLD_TUNING.md](THRESHOLD_TUNING.md)).",
              "- False positives: the baseline reaches zero only because two exceptions written for that same baseline "
              "suppress 119 matches ([VALIDATION_RESULTS.md](VALIDATION_RESULTS.md)).",
              "", f"## 5. Never verified end to end ({len(NOT_VERIFIED)})", ""]
    lines += [f"- {item}" for item in NOT_VERIFIED]
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Generate the 'what I missed' report")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    body = render()
    if args.check:
        try:
            with open(REPORT, encoding="utf-8") as fh:
                sys.exit(0 if fh.read().replace("\r\n", "\n") == body else 1)
        except FileNotFoundError:
            sys.exit(1)
    with open(REPORT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body)
    print(f"wrote {os.path.relpath(REPORT, ROOT)}")


if __name__ == "__main__":
    main()
