#!/usr/bin/env python3
"""
Generate docs/coverage/LEADERBOARD.md (roadmap F98): every single-event rule ranked by the
evidence behind it, with what each one is missing.

    CYBERPULSE_LAB_MODE=true python scripts/leaderboard.py           # write
    CYBERPULSE_LAB_MODE=true python scripts/leaderboard.py --check   # exit 1 if stale

Nothing new is scored here. Each column is joined from an existing generated report:
the review heuristic (coverage/QUALITY.md), scripted-attack recall and raw baseline matches
(VALIDATION_RESULTS.md), and evasion results (EVASION.md). The ranking orders rules for
review work; it is not a measure of how well any of them detects real attacks.
"""

import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
os.environ.setdefault("CYBERPULSE_LAB_MODE", "true")

from scripts.coverage_report import rule_quality  # noqa: E402
from scripts.evasion_report import results as evasion_results  # noqa: E402
from scripts.validate_detections import run_scripted  # noqa: E402

REPORT = os.path.join(ROOT, "docs", "coverage", "LEADERBOARD.md")
MISSING = {
    "positive_samples": "positive sample", "negative_samples": "negative sample",
    "scripted_generator": "scripted attack generator", "baseline_fp": "quiet on the benign baseline",
    "metadata": "complete metadata", "shared_data_source": "a second rule on its data source",
}


def rows():
    scripted = run_scripted()
    evasion = {}
    for case in evasion_results():
        evasion.setdefault(case["rule"], []).append(case)
    out = []
    for q in rule_quality():
        cases = evasion.get(q["rule"], [])
        bypasses = [c["id"] for c in cases if c["actual"] == "bypass"]
        run = scripted.get(q["rule"])
        missing = [MISSING[k] for k, v in q["parts"].items() if v == 0]
        if q["parts"]["metadata"] and q["parts"]["metadata"] < 20:
            missing.append("some metadata")
        if not cases:
            missing.append("evasion tests")
        if bypasses:
            missing.append(f"closes {len(bypasses)} known bypass(es): {', '.join(bypasses)}")
        out.append({
            "rule": q["rule"], "title": q["title"], "quality": q["score"],
            "recall": f"{run['detected']}/{run['runs']}" if run else "no generator",
            "baseline": q["baseline_fp"],
            "evasion": f"{len(cases) - len(bypasses)}/{len(cases)} caught" if cases else "not tested",
            "bypasses": len(bypasses), "missing": missing,
        })
    # Most evidence first. Untested evasion counts as missing, like a known bypass, so testing a
    # rule never lowers its rank relative to not testing it; baseline noise breaks the tie
    out.sort(key=lambda r: (-r["quality"], len(r["missing"]), r["baseline"], r["rule"]))
    return out


def render():
    ranked = rows()
    tested = [r for r in ranked if r["evasion"] != "not tested"]
    lines = [
        "# Detection Quality Leaderboard",
        "",
        "> Generated by `CYBERPULSE_LAB_MODE=true python scripts/leaderboard.py` from the other generated",
        "> reports. It ranks rules by the **evidence behind them** so review effort goes to the weakest",
        "> first. All data is synthetic and the same author wrote the rules and the tests: a high",
        "> rank means well-tested here, not effective against real attacks.",
        "",
        "Ranking: quality heuristic ([QUALITY.md](QUALITY.md)), then fewer missing items (a rule with",
        "no evasion tests counts the same as one with a known bypass, see [EVASION.md](../EVASION.md)),",
        "then fewer benign baseline matches before exceptions",
        "([VALIDATION_RESULTS.md](../VALIDATION_RESULTS.md)). Correlation rules are not ranked:",
        "the heuristic does not cover them yet.",
        "",
        f"{len(ranked)} rules. {sum(1 for r in ranked if r['quality'] == 100)} score 100 on the heuristic; "
        f"{len(tested)} have evasion tests, and {sum(1 for r in tested if r['bypasses'])} of those",
        f"are bypassed by at least one variant. {sum(1 for r in ranked if not r['missing'])} rules are missing nothing.",
        "",
        "| # | Rule | Quality | Scripted recall | Baseline matches | Evasion | Missing |",
        "| ---: | :--- | ---: | :--- | ---: | :--- | :--- |",
    ]
    for i, r in enumerate(ranked, 1):
        lines.append(f"| {i} | {r['rule']}: {r['title']} | {r['quality']} | {r['recall']} | {r['baseline']} | "
                     f"{r['evasion']} | {'; '.join(r['missing']) or '-'} |")
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Generate the detection quality leaderboard")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    body = render()
    if args.check:
        try:
            with open(REPORT, encoding="utf-8") as fh:
                sys.exit(0 if fh.read().replace("\r\n", "\n") == body else 1)
        except FileNotFoundError:
            sys.exit(1)
    with open(REPORT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body)
    print(f"wrote {os.path.relpath(REPORT, ROOT)}")


if __name__ == "__main__":
    main()
