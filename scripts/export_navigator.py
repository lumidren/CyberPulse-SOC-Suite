#!/usr/bin/env python3
"""
Export rule coverage as a MITRE ATT&CK Navigator layer (heatmap).

    python scripts/export_navigator.py           # write docs/coverage/attack_navigator_layer.json
    python scripts/export_navigator.py --check   # exit 1 if the committed layer is stale

Open the JSON in https://mitre-attack.github.io/attack-navigator/ ("Open Existing
Layer" -> "Upload from local"). Score = number of rules tagged with the technique.
Coverage here means "a lab rule exists", not "detection is proven on real traffic".
"""

import argparse
import json
import os
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from soar.sigma_engine import SigmaEngine  # noqa: E402

LAYER_PATH = os.path.join(ROOT, "docs", "coverage", "attack_navigator_layer.json")


def build_layer():
    by_technique = defaultdict(list)
    for rule in SigmaEngine().rules:
        for technique in rule.technique_ids:
            by_technique[technique].append(rule.soar.get("soc_rule_id", rule.id))
    techniques = [
        {
            "techniqueID": tid,
            "score": len(rule_ids),
            "comment": "Lab rules (synthetic-tested only): " + ", ".join(sorted(rule_ids)),
            "enabled": True,
            "showSubtechniques": "." in tid,
        }
        for tid, rule_ids in sorted(by_technique.items())
    ]
    max_score = max((t["score"] for t in techniques), default=1)
    return {
        "name": "CyberPulse SOC Lab - Rule Coverage",
        "versions": {"attack": "16", "navigator": "5.1.0", "layer": "4.5"},
        "domain": "enterprise-attack",
        "description": ("Techniques with at least one CyberPulse Sigma rule. Generated by scripts/export_navigator.py. "
                        "Rules are tested on synthetic events only; coverage is not proven detection."),
        "techniques": techniques,
        "gradient": {"colors": ["#ffe766", "#8ec843"], "minValue": 1, "maxValue": max(max_score, 2)},
        "legendItems": [{"label": "1 rule", "color": "#ffe766"}, {"label": f"{max(max_score, 2)}+ rules", "color": "#8ec843"}],
        "hideDisabled": False,
        "showTacticRowBackground": True,
        "tacticRowBackground": "#205b8f",
    }


def render():
    return json.dumps(build_layer(), indent=2) + "\n"


def main():
    parser = argparse.ArgumentParser(description="Export an ATT&CK Navigator coverage layer")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    body = render()
    if args.check:
        try:
            with open(LAYER_PATH, encoding="utf-8") as fh:
                current = fh.read().replace("\r\n", "\n")
        except FileNotFoundError:
            current = ""
        sys.exit(0 if current == body else 1)
    os.makedirs(os.path.dirname(LAYER_PATH), exist_ok=True)
    with open(LAYER_PATH, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body)
    print(f"wrote {LAYER_PATH} ({len(build_layer()['techniques'])} techniques)")


if __name__ == "__main__":
    main()
