#!/usr/bin/env python3
"""
Automated purple-team report: what ran, what fired, what missed (roadmap F23).

    CYBERPULSE_LAB_MODE=true python scripts/purple_team_report.py           # write docs/PURPLE_TEAM_REPORT.md
    CYBERPULSE_LAB_MODE=true python scripts/purple_team_report.py --check   # exit 1 if stale

Replays every purple-team scenario (simulator/purple_team_runner.py) and every scripted
technique test through the full pipeline with the production default policy
(APPROVAL_REQUIRED), and records for each step the rule that was expected, the rule
that fired, and what the pipeline decided to do. Timings are left out so the report
is reproducible; latency is reported separately (scripts/latency_report.py).

What ran here is synthetic telemetry written by the rule author. For a report on
real attack activity, run atomics or Caldera in your own lab and use
scripts/caldera_compare.py (docs/ATOMIC_RED_TEAM.md, docs/CALDERA.md).
"""

import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from scripts.validate_detections import EXPECTED_RULE  # noqa: E402
from simulator.attack_simulator import SCRIPTED_GENERATORS  # noqa: E402
from simulator.purple_team_runner import SCENARIOS  # noqa: E402
from soar.soar_engine import SOAROrchestrator  # noqa: E402

REPORT = os.path.join(ROOT, "docs", "PURPLE_TEAM_REPORT.md")


def _run(orchestrator, event, expected):
    alert = orchestrator.process_event(event)
    rule = (alert or {}).get("rule") or {}
    fired = rule.get("rule_id")
    if not alert:
        verdict = "MISSED"
    elif fired == expected:
        verdict = "DETECTED"
    elif expected in rule.get("also_matched", []):
        verdict = "DETECTED (not top match)"
    else:
        verdict = "WRONG RULE"
    return {
        "technique": event.get("technique_id"),
        "expected": expected,
        "fired": fired,
        "also": rule.get("also_matched", []),
        "verdict": verdict,
        "decision": ((alert or {}).get("policy_decision") or {}).get("execution_intent", "-"),
        "action": ((alert or {}).get("containment_action") or {}).get("action_type", "-"),
        "status": ((alert or {}).get("containment_action") or {}).get("status", "-"),
    }


def build():
    sections = []
    for key, scenario in SCENARIOS.items():
        orchestrator = SOAROrchestrator(policy_mode="APPROVAL_REQUIRED")
        rows = [dict(_run(orchestrator, stage["generator"](), stage["expected_rule"]),
                     step=f"{stage['sequence']}. {stage['name']}") for stage in scenario["stages"]]
        sections.append((f"Scenario: {scenario['name']}", key, rows))
    orchestrator = SOAROrchestrator(policy_mode="APPROVAL_REQUIRED")
    rows = [dict(_run(orchestrator, generator(), EXPECTED_RULE[name]), step=generator.__name__)
            for name, generator in SCRIPTED_GENERATORS]
    sections.append(("Single-technique tests", "SCRIPTED_GENERATORS", rows))
    return sections


def render():
    sections = build()
    all_rows = [r for _, _, rows in sections for r in rows]
    detected = sum(1 for r in all_rows if r["verdict"].startswith("DETECTED"))
    lines = [
        "# Purple-Team Report",
        "",
        "> Generated by `scripts/purple_team_report.py` (lab mode). Synthetic telemetry written by the",
        "> rule author; this is a regression check of the pipeline, not evidence of real-world detection.",
        "",
        f"**{detected}/{len(all_rows)} steps detected by the expected rule.** Policy: APPROVAL_REQUIRED "
        "(the production default), so containment is proposed for analyst approval, not executed.",
        "",
    ]
    for title, source, rows in sections:
        lines += [f"## {title}", "", f"Source: `{source}`", "",
                  "| Step | Technique | Expected | Fired | Result | Decision | Proposed action | Status |",
                  "| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |"]
        for r in rows:
            fired = r["fired"] or "-"
            if r["also"]:
                fired += f" (+{', '.join(r['also'])})"
            lines.append(f"| {r['step']} | {r['technique']} | {r['expected']} | {fired} | {r['verdict']} | "
                         f"{r['decision']} | {r['action']} | {r['status']} |")
        lines.append("")
    missed = [r for r in all_rows if not r["verdict"].startswith("DETECTED")]
    lines += ["## What missed", ""]
    lines += [f"- {r['step']} ({r['technique']}): expected {r['expected']}, got {r['fired'] or 'nothing'}"
              for r in missed] or ["Nothing in this run. Techniques the lab cannot emulate or detect are listed in "
                                   "[coverage/GAPS.md](coverage/GAPS.md)."]
    lines.append("")
    return "\n".join(lines)


def main():
    from simulator.lab_guard import lab_mode_enabled
    if not lab_mode_enabled():
        sys.exit("Refusing to run: set CYBERPULSE_LAB_MODE=true (lab use only).")
    parser = argparse.ArgumentParser(description="What ran, what fired, what missed")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    body = render()
    if args.check:
        try:
            with open(REPORT, encoding="utf-8") as fh:
                sys.exit(0 if fh.read().replace("\r\n", "\n") == body else 1)
        except FileNotFoundError:
            sys.exit(1)
    with open(REPORT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body)
    print(f"wrote {os.path.relpath(REPORT, ROOT)}")


if __name__ == "__main__":
    main()
