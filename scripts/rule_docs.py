#!/usr/bin/env python3
"""
Generated per-rule documentation.

    python scripts/rule_docs.py           # write the docs
    python scripts/rule_docs.py --check   # exit 1 if any is stale

Outputs:
  * docs/FALSE_POSITIVES.md - known false-positive scenarios for every rule (roadmap E94),
    with what the seeded benign baseline actually triggered and the exceptions in force.
  * docs/runbooks/<SOC id>.md and an index - a response runbook per detection (roadmap F78).
  * docs/rules/<SOC id>.md and an index - a detection write-up per rule: mechanics in plain
    words, telemetry, validation evidence and tuning (roadmap F83).
"""

import argparse
import os
import sys
from collections import Counter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
os.environ.setdefault("CYBERPULSE_LAB_MODE", "true")

from scripts.validate_detections import BASELINE_COUNT, BASELINE_SEED  # noqa: E402
from simulator.benign_baseline import generate_baseline  # noqa: E402
from scripts.coverage_report import data_source_of  # noqa: E402
from scripts.document_actions import CONTAINMENT  # noqa: E402
from soar.action_tiers import requires_approval, tier_for  # noqa: E402
from soar.playbooks import PlaybookRegistry  # noqa: E402
from soar.resilient_containment import ROLLBACK_PLAYBOOKS  # noqa: E402
from soar.rule_exceptions import ExceptionRegistry  # noqa: E402
from soar.sigma_correlation import CorrelationEngine  # noqa: E402
from soar.sigma_engine import SigmaEngine  # noqa: E402

DOCS = os.path.join(ROOT, "docs")


def all_rules():
    return sorted(SigmaEngine().rules + CorrelationEngine().rules, key=lambda r: r.soar.get("soc_rule_id", r.id or ""))


def soc_id(rule):
    return rule.soar.get("soc_rule_id", rule.id)


def baseline_matches():
    """Single-event rule matches on the seeded benign baseline, before exceptions."""
    engine = SigmaEngine()
    counts = Counter()
    for event in generate_baseline(BASELINE_COUNT, BASELINE_SEED):
        for rule in engine.match_all(event):
            counts[soc_id(rule)] += 1
    return counts


def render_false_positives():
    counts = baseline_matches()
    exceptions = ExceptionRegistry().exceptions
    lines = [
        "# Known False Positives per Rule",
        "",
        "> Generated by `python scripts/rule_docs.py` from each rule's `falsepositives` field, the seeded",
        f"> benign baseline ({BASELINE_COUNT} events, seed {BASELINE_SEED}) and `rules/exceptions.yml`.",
        "",
        "Scenarios are what the rule author expects in real environments; none has been observed on real",
        "traffic here. *Baseline matches* are real counts on the synthetic benign traffic, before exceptions.",
        "How to tune each one: [TUNING.md](TUNING.md).",
        "",
    ]
    for rule in all_rules():
        rid = soc_id(rule)
        kind = "correlation" if hasattr(rule, "rule_names") else "rule"
        lines += [f"## {rid}: {rule.title}", "",
                  f"`{rule.file}` ({kind}, level {rule.level})", ""]
        lines += [f"- {fp}" for fp in rule.doc.get("falsepositives") or []]
        if kind == "rule":
            lines.append(f"- Baseline matches before exceptions: **{counts.get(rid, 0)}**")
        active = [e for e in exceptions if e.rule == rid]
        for exc in active:
            lines.append(f"- Exception `{exc.id}` (owner {exc.owner}, expires {exc.expires.isoformat()}): {exc.reason.strip()}")
        lines.append("")
    return "\n".join(lines)


def _fields(rule):
    """Event fields the rule looks at (for 'what to check')."""
    selections = rule.selections if hasattr(rule, "selections") else {}
    if hasattr(rule, "base_rules"):
        selections = {k: v for b in rule.base_rules for k, v in b.selections.items()}
    fields = []
    for sel in selections.values():
        for item in sel if isinstance(sel, list) else [sel]:
            if isinstance(item, dict):
                fields += [spec.split("|")[0] for spec in item]
    return sorted(set(fields))


def render_runbook(rule, registry, exceptions):
    rid = soc_id(rule)
    matched = rule.as_matched_rule()
    playbook = registry.select(matched)
    action = (playbook.action if playbook and playbook.action else None) or matched.get("action_recommended")
    lines = [f"# Runbook: {rid} {rule.title}", "",
             "> Generated by `python scripts/rule_docs.py` from the rule, its playbook and the containment",
             "> catalogue. Edit those sources, not this page.", "",
             "## What fired", "",
             f"{' '.join(str(rule.doc.get('description', '')).split())}", "",
             f"- Severity: **{matched['severity']}** · ATT&CK: {', '.join(rule.technique_ids) or '-'}",
             f"- Rule file: `{rule.file}` · Data source: {data_source_of(rule)}", "",
             "## Triage", "",
             f"Playbook: `{playbook.name if playbook else 'none'}`.", ""]
    lines += [f"{i}. {task}" for i, task in enumerate(playbook.tasks if playbook else [], 1)] or ["1. Confirm the alert against the raw event."]
    lines += ["", "Fields to check in the event: " + (", ".join(f"`{f}`" for f in _fields(rule)) or "-") + ".", "",
              "## Response", ""]
    if action in CONTAINMENT:
        reversibility = (ROLLBACK_PLAYBOOKS.get(action) or ("NONE",))[0]
        lines += [f"- Proposed action: `{action}` ({tier_for(action)}, "
                  f"{'always needs approval' if requires_approval(action) else 'approval unless opt-in automatic mode'}, "
                  f"rollback {reversibility}).",
                  f"- What it does: {CONTAINMENT[action][0]}",
                  f"- How it can go wrong: {CONTAINMENT[action][1]}",
                  "- Before approving: collect or check the volatile evidence package on the incident; "
                  "confirm the target is not a protected asset or account."]
    else:
        lines += [f"- No containment is proposed (`{action}`): alert and investigate. If you decide to act, "
                  "propose an action on the incident (`POST /api/incidents/<id>/propose`); it still needs approval."]
    lines += ["", "## Known false positives", ""]
    lines += [f"- {fp}" for fp in rule.doc.get("falsepositives") or []]
    lines += [f"- Exception `{e.id}` in force until {e.expires.isoformat()}: {' '.join(e.reason.split())}"
              for e in exceptions if e.rule == rid]
    lines += ["", "## Escalate when", "",
              "- The activity continues after containment, or appears on a second host or account.",
              "- A protected asset, privileged account or production service is involved.",
              "- You cannot rule out real attacker activity within the playbook's steps.", "",
              "## If the alert was wrong", "",
              "Open an appeal on the incident ([APPEALS.md](../APPEALS.md)) and tune it ([TUNING.md](../TUNING.md)).", ""]
    return "\n".join(lines)


def render_runbook_index():
    lines = ["# Detection Runbooks", "", "> Generated by `python scripts/rule_docs.py`. One page per detection.", "",
             "| Rule | Title | Severity |", "| :--- | :--- | :--- |"]
    lines += [f"| [{soc_id(r)}]({soc_id(r)}.md) | {r.title} | {r.as_matched_rule()['severity']} |" for r in all_rules()]
    lines.append("")
    return "\n".join(lines)


MODIFIER_WORDS = {"contains": "contains", "startswith": "starts with", "endswith": "ends with", "re": "matches regex",
                  "gte": "is at least", "gt": "is more than", "lte": "is at most", "lt": "is less than",
                  "exists": "is present", "cidr": "is in network", "all": "(all of)"}


def _describe_selection(name, sel):
    if isinstance(sel, list) and all(isinstance(x, dict) for x in sel):
        return f"- `{name}`: any of " + "; ".join(_describe_selection(name, x)[len(f"- `{name}`: "):] for x in sel)
    if not isinstance(sel, dict):
        return f"- `{name}`: keywords {sel}"
    parts = []
    for spec, value in sel.items():
        field, *mods = spec.split("|")
        verb = " ".join(MODIFIER_WORDS.get(m, m) for m in mods) or "equals"
        if mods == ["exists"]:
            parts.append(f"`{field}` {'is present' if value else 'is absent'}")
            continue
        values = value if isinstance(value, list) else [value]
        shown = ", ".join(f"`{v}`" for v in values[:8]) + (f" (+{len(values) - 8} more)" if len(values) > 8 else "")
        joiner = "all of" if "all" in mods else ("one of" if len(values) > 1 else "")
        parts.append(f"`{field}` {verb.replace('(all of)', '').strip()} {joiner} {shown}".replace("  ", " "))
    return f"- `{name}`: " + " AND ".join(parts)


def _tests_mentioning(rid):
    folder = os.path.join(ROOT, "tests")
    found = []
    for name in sorted(os.listdir(folder)):
        if name.endswith(".py"):
            with open(os.path.join(folder, name), encoding="utf-8") as fh:
                if f'"{rid}"' in fh.read():
                    found.append(name)
    return found


def _evidence(rule, samples, scripted, evasions, quality, baseline):
    rid = soc_id(rule)
    pos, neg = samples.get(os.path.basename(rule.file), (0, 0))
    rows = [f"- Samples in `rules/tests/`: {pos} positive, {neg} negative" if not hasattr(rule, "base_rules")
            else "- Sequence tests: " + (", ".join(f"`tests/{t}`" for t in _tests_mentioning(rid)) or "none"),
            f"- Scripted attack generator: {'yes' if rid in scripted else 'no'}"]
    if not hasattr(rule, "base_rules"):
        rows.append(f"- Matches on the 600-event benign baseline before exceptions: {baseline.get(rid, 0)}")
    if rid in quality:
        rows.append(f"- Quality score: {quality[rid]}/100 ([QUALITY.md](../coverage/QUALITY.md))")
    mine = [e for e in evasions if e["rule"] == rid]
    if mine:
        rows.append("- Evasion cases ([EVASION.md](../EVASION.md)): " + "; ".join(
            f"{e['id']} {e['trick']} -> {'BYPASS' if e['actual'] == 'bypass' else 'detected'}" for e in mine))
    return rows


def render_writeup(rule, ctx):
    rid = soc_id(rule)
    lines = [f"# {rid}: {rule.title}", "",
             "> Generated by `python scripts/rule_docs.py` from the rule and the test evidence.", "",
             f"**Level** {rule.level} · **ATT&CK** {', '.join(rule.technique_ids) or '-'} · "
             f"**Version** {rule.soar.get('version', '?')} · `{rule.file}` · [Runbook](../runbooks/{rid}.md)", "",
             "## What it detects", "", " ".join(str(rule.doc.get("description", "")).split()), "",
             "## How it works", ""]
    if hasattr(rule, "base_rules"):
        cond = f"{MODIFIER_WORDS.get(rule.op, rule.op)} {rule.threshold}".replace("equals", "exactly")
        what = {"event_count": "events", "value_count": f"distinct values of `{rule.value_field}`",
                "temporal": "of the listed base rules"}[rule.type]
        lines += [f"A **{rule.type}** correlation: within {rule.timespan} s, grouped by "
                  f"{', '.join(f'`{g}`' for g in rule.group_by) or 'nothing'}, it fires when the number of {what} "
                  f"{cond}. One burst raises one alert. Base rules:", ""]
        for base in rule.base_rules:
            lines += [f"`{base.doc.get('name')}` ({base.title}):", ""]
            lines += [_describe_selection(n, s) for n, s in base.selections.items()]
            base_cond = base.doc["detection"]["condition"]
            lines += [f"- condition: `{' / '.join(base_cond) if isinstance(base_cond, list) else base_cond}`", ""]
    else:
        lines += [_describe_selection(n, s) for n, s in rule.selections.items()]
        cond = rule.doc["detection"]["condition"]
        lines += [f"- condition: `{cond if isinstance(cond, str) else ' / '.join(cond)}`", ""]
    logsource = "/".join(str(v) for v in (rule.logsource.get("product"), rule.logsource.get("category") or rule.logsource.get("service")))
    lines += ["## Telemetry it needs", "", f"{data_source_of(rule)} (logsource `{logsource}`). "
              "If that source is not collected, the rule cannot fire: see [DATA_SOURCES.md](../coverage/DATA_SOURCES.md).", "",
              "## Evidence it works (synthetic data only)", ""]
    lines += _evidence(rule, *ctx)
    lines += ["", "## Tuning", ""]
    lines += [f"- Expected false positive: {fp}" for fp in rule.doc.get("falsepositives") or []]
    lines += ["- Prefer an expiring exception for one known-benign pattern; change the logic (with a version bump) only "
              "when it is wrong for everyone. See [TUNING.md](../TUNING.md).", "",
              "## Other formats", "",
              "Generated SIEM queries (review before use): " + (
                  ", ".join(f"[{t}](../../rules/converted/{t}/{os.path.splitext(os.path.basename(rule.file))[0]}.{ext})"
                            for t, ext in (("splunk", "spl"), ("elastic", "lucene"), ("kql", "kql")))
                  if not hasattr(rule, "base_rules") else "correlations are not converted (see rules/sigma/correlations/README.md)") + ".", ""]
    return "\n".join(lines)


def _writeup_context():
    from scripts.coverage_report import _sample_counts, rule_quality
    from scripts.evasion_report import results as evasion_results
    from scripts.validate_detections import EXPECTED_RULE
    quality = {r["rule"]: r["score"] for r in rule_quality()}
    return (_sample_counts(), set(EXPECTED_RULE.values()), evasion_results(), quality, baseline_matches())


def render_writeup_index():
    lines = ["# Detection Write-ups", "", "> Generated by `python scripts/rule_docs.py`. One page per rule: mechanics, telemetry, "
             "evidence and tuning.", "", "| Rule | Title | ATT&CK | Level |", "| :--- | :--- | :--- | :--- |"]
    lines += [f"| [{soc_id(r)}]({soc_id(r)}.md) | {r.title} | {', '.join(r.technique_ids)} | {r.level} |" for r in all_rules()]
    lines.append("")
    return "\n".join(lines)


def _writeup_outputs():
    cache = {}

    def ctx():
        if "ctx" not in cache:
            cache["ctx"] = _writeup_context()
        return cache["ctx"]
    out = {os.path.join(DOCS, "rules", "README.md"): render_writeup_index}
    for rule in all_rules():
        out[os.path.join(DOCS, "rules", f"{soc_id(rule)}.md")] = (lambda r=rule: render_writeup(r, ctx()))
    return out


def _runbook_outputs():
    registry, exceptions = PlaybookRegistry(), ExceptionRegistry().exceptions
    out = {os.path.join(DOCS, "runbooks", "README.md"): render_runbook_index}
    for rule in all_rules():
        out[os.path.join(DOCS, "runbooks", f"{soc_id(rule)}.md")] = (lambda r=rule: render_runbook(r, registry, exceptions))
    return out


OUTPUTS = {os.path.join(DOCS, "FALSE_POSITIVES.md"): render_false_positives, **_runbook_outputs(), **_writeup_outputs()}


def main():
    parser = argparse.ArgumentParser(description="Generate per-rule documentation")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, render in OUTPUTS.items():
        body = render()
        if args.check:
            try:
                with open(path, encoding="utf-8") as fh:
                    if fh.read().replace("\r\n", "\n") != body:
                        stale.append(path)
            except FileNotFoundError:
                stale.append(path)
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(body)
    if args.check:
        for path in stale:
            print("stale:", os.path.relpath(path, ROOT))
        sys.exit(1 if stale else 0)
    print(f"wrote {len(OUTPUTS)} file(s)")


if __name__ == "__main__":
    main()
