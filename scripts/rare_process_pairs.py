#!/usr/bin/env python3
"""
Train the parent -> child process baseline on the seeded benign traffic and score
the rule samples against it (roadmap F13).

    python scripts/rare_process_pairs.py           # write docs/BEHAVIORAL_BASELINE.md
    python scripts/rare_process_pairs.py --check   # exit 1 if the committed report is stale

All inputs are synthetic and in the repo: the benign baseline (seed 1337) and the
positive samples in rules/tests/. The result shows the mechanism works on lab data;
it says nothing about how noisy the signal would be on a real estate.
"""

import argparse
import os
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from scripts.validate_detections import BASELINE_COUNT, BASELINE_SEED  # noqa: E402
from simulator.benign_baseline import generate_baseline  # noqa: E402
from soar.process_baseline import ProcessPairBaseline, process_pair  # noqa: E402

REPORT = os.path.join(ROOT, "docs", "BEHAVIORAL_BASELINE.md")
SAMPLES_DIR = os.path.join(ROOT, "rules", "tests")


def sample_events(kind):
    for name in sorted(os.listdir(SAMPLES_DIR)):
        if name.endswith(".yml"):
            with open(os.path.join(SAMPLES_DIR, name), encoding="utf-8") as fh:
                doc = yaml.safe_load(fh) or {}
            for sample in doc.get(kind) or []:
                if process_pair(sample["event"]):
                    yield doc["rule"], sample["name"], sample["event"]


def build():
    baseline = ProcessPairBaseline().learn_many(generate_baseline(BASELINE_COUNT, BASELINE_SEED))
    scored = {kind: [(rule, name, baseline.score(event)) for rule, name, event in sample_events(kind)]
              for kind in ("positive", "negative")}
    return baseline, scored


def render():
    baseline, scored = build()
    flagged = lambda rows: sum(1 for *_, s in rows if s["verdict"] in {"RARE", "NEVER_SEEN"})  # noqa: E731
    lines = [
        "# Behavioural Baseline: Rare Parent-Child Processes",
        "",
        "> Generated by `python scripts/rare_process_pairs.py`. Synthetic lab data only.",
        "",
        f"Trained on **{baseline.total} process-creation events** from the seeded benign baseline "
        f"({BASELINE_COUNT} events, seed {BASELINE_SEED}). A pair seen {baseline.rare_threshold} time(s) or "
        "fewer is *rare*; a pair never seen is *never seen*. Either one is a triage hint, not an alert.",
        "",
        "## Baseline pairs",
        "",
        "| Parent -> child | Seen |",
        "| :--- | ---: |",
    ]
    lines += [f"| `{p} -> {c}` | {n} |" for (p, c), n in sorted(baseline.counts.items(), key=lambda kv: (-kv[1], kv[0]))]
    for kind, label in (("positive", "Attack samples"), ("negative", "Benign near-miss samples")):
        rows = scored[kind]
        lines += ["", f"## {label} ({flagged(rows)}/{len(rows)} flagged)", "",
                  "| Rule sample | Pair | Verdict |", "| :--- | :--- | :--- |"]
        lines += [f"| `{rule}`: {name} | `{s['pair']}` | {s['verdict']} |" for rule, name, s in rows]
    negatives = scored["negative"]
    lines += ["", "## What this shows", "",
              f"The benign baseline contains only **{len(baseline.counts)} distinct pairs**, so "
              f"{flagged(negatives)}/{len(negatives)} benign near-miss samples are flagged as well as the attacks.",
              "On this data the signal does **not** separate attack from benign; it only proves the mechanism",
              "(count, compare, flag) works. A useful baseline needs weeks of real process telemetry from the",
              "estate it will protect. Negative samples are near-misses written for the Sigma rules, not a",
              "representative benign population, so they do not measure precision either.", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    body = render()
    if args.check:
        try:
            with open(REPORT, encoding="utf-8") as fh:
                sys.exit(0 if fh.read().replace("\r\n", "\n") == body else 1)
        except FileNotFoundError:
            sys.exit(1)
    with open(REPORT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body)
    print(f"wrote {os.path.relpath(REPORT, ROOT)}")


if __name__ == "__main__":
    main()
