#!/usr/bin/env python3
"""
Coverage analysis generated from the Sigma rules.

    python scripts/coverage_report.py           # write docs/coverage/*.md
    python scripts/coverage_report.py --check   # exit 1 if any committed report is stale

Reports:
  * DATA_SOURCES.md - which log sources feed which rules/techniques, and what
    is lost if a source goes dark.
  * GAPS.md - target techniques (rules/coverage_targets.yml plus everything the
    attack simulator emits) that no rule covers.
  * QUALITY.md - per-rule quality score from samples, baseline false
    positives, metadata and data-source reuse.
"""

import argparse
import os
import re
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

import yaml  # noqa: E402

from soar.sigma_correlation import CorrelationEngine  # noqa: E402
from soar.sigma_engine import SigmaEngine  # noqa: E402

OUT = os.path.join(ROOT, "docs", "coverage")
TARGETS_PATH = os.path.join(ROOT, "rules", "coverage_targets.yml")
SIMULATOR_PATH = os.path.join(ROOT, "simulator", "attack_simulator.py")
SAMPLES_DIR = os.path.join(ROOT, "rules", "tests")
TECHNIQUE_RE = re.compile(r"\bT\d{4}(?:\.\d{3})?\b")

# Logsource -> human data source (what must be collected for the rule to work)
DATA_SOURCE_NAMES = {
    ("windows", "process_creation"): "Sysmon Event 1 (process creation) / Security 4688 with command line",
    ("windows", "process_access"): "Sysmon Event 10 (process access)",
    ("windows", "file_event"): "Sysmon Event 11 (file create)",
    ("windows", "registry_set"): "Sysmon Event 13 (registry value set)",
    ("windows", "wmi_event"): "Sysmon Events 19-21 (WMI activity)",
    ("windows", "security"): "Windows Security log (Advanced Audit Policy)",
    ("windows", "sysmon"): "Sysmon (driver load, Event 6)",
    ("windows", "system"): "Windows System log (Service Control Manager)",
    ("aws", "cloudtrail"): "AWS CloudTrail (management events)",
    ("azure", "signinlogs"): "Entra ID sign-in logs",
    ("azure", "auditlogs"): "Entra ID audit logs",
}


def data_source_of(rule):
    ls = rule.logsource
    key = (ls.get("product"), ls.get("category") or ls.get("service"))
    return DATA_SOURCE_NAMES.get(key, f"{key[0]}/{key[1]}")


def detection_rules():
    """Single-event rules plus correlation rules: everything that can raise an alert."""
    return SigmaEngine().rules + CorrelationEngine().rules


def data_sources():
    table = defaultdict(lambda: {"rules": [], "techniques": set()})
    for rule in detection_rules():
        entry = table[data_source_of(rule)]
        entry["rules"].append(rule.soar.get("soc_rule_id", rule.id))
        entry["techniques"].update(rule.technique_ids)
    return table


def render_data_sources():
    table = data_sources()
    all_techniques = set().union(*(e["techniques"] for e in table.values()))
    lines = [
        "# Data-Source Coverage",
        "",
        "> Generated by `python scripts/coverage_report.py`. Do not edit by hand.",
        "",
        "Which telemetry each rule depends on. *Unique techniques* are covered only by that",
        "source: if it stops arriving (agent removed, audit policy changed, log not shipped),",
        "those techniques lose all coverage.",
        "",
        "| Data source | Rules | Techniques | Unique techniques |",
        "| :--- | ---: | ---: | :--- |",
    ]
    for source, entry in sorted(table.items(), key=lambda kv: -len(kv[1]["rules"])):
        others = set().union(*(e["techniques"] for s, e in table.items() if s != source)) if len(table) > 1 else set()
        unique = sorted(entry["techniques"] - others)
        lines.append(f"| {source} | {len(entry['rules'])} | {len(entry['techniques'])} | {', '.join(unique) or '-'} |")
    lines += ["", f"**{len(all_techniques)} techniques** across **{sum(len(e['rules']) for e in table.values())} rules** "
              f"and **{len(table)} data sources**.", ""]
    return "\n".join(lines)


def covered_techniques():
    return {tid for rule in detection_rules() for tid in rule.technique_ids}


def simulated_techniques():
    with open(SIMULATOR_PATH, encoding="utf-8") as fh:
        return set(TECHNIQUE_RE.findall(fh.read()))


def load_targets():
    with open(TARGETS_PATH, encoding="utf-8") as fh:
        return (yaml.safe_load(fh) or {}).get("targets", {})


def gaps():
    """Uncovered targets: (technique, entry) with entry from the targets file or a simulator stub."""
    targets = dict(load_targets())
    for tid in simulated_techniques() - set(targets):
        targets[tid] = {"name": "(emitted by the attack simulator)", "tactic": "-", "why": "Simulated in the lab"}
    covered = covered_techniques()
    # A parent target (T1110) counts as covered when a sub-technique rule exists (T1110.001).
    # The reverse is not true: a rule for T1003 does not prove coverage of T1003.001.
    covered_parents = {tid.split(".")[0] for tid in covered}
    uncovered = {tid: e for tid, e in targets.items() if tid not in covered and not ("." not in tid and tid in covered_parents)}
    return targets, uncovered


def render_gaps():
    targets, uncovered = gaps()
    simulated = simulated_techniques()
    accepted = {t: e for t, e in uncovered.items() if e.get("blocker")}
    open_gaps = {t: e for t, e in uncovered.items() if not e.get("blocker")}
    lines = [
        "# Detection Gap Report",
        "",
        "> Generated by `python scripts/coverage_report.py` from `rules/coverage_targets.yml`,",
        "> the techniques emitted by `simulator/attack_simulator.py`, and the Sigma rule tags.",
        "",
        f"**{len(targets) - len(uncovered)}/{len(targets)} target techniques have at least one rule.** "
        "A rule existing is not proof of detection: rules are tested on synthetic events only.",
        "",
        "## Open gaps (no rule, no recorded blocker)",
        "",
    ]
    if open_gaps:
        lines += ["| Technique | Name | Tactic | Why it matters | Simulated? |", "| :--- | :--- | :--- | :--- | :---: |"]
        lines += [f"| {t} | {e['name']} | {e['tactic']} | {e['why']} | {'yes' if t in simulated else 'no'} |"
                  for t, e in sorted(open_gaps.items())]
    else:
        lines.append("None.")
    lines += ["", "## Accepted gaps (blocked on telemetry or tuning)", ""]
    if accepted:
        lines += ["| Technique | Name | Tactic | Blocker |", "| :--- | :--- | :--- | :--- |"]
        lines += [f"| {t} | {e['name']} | {e['tactic']} | {e['blocker']} |" for t, e in sorted(accepted.items())]
    else:
        lines.append("None.")
    undetected_sim = sorted(simulated - covered_techniques())
    lines += ["", "## Simulated but undetected", "",
              (", ".join(undetected_sim) if undetected_sim else "None: every technique the simulator emits has a rule."), ""]
    return "\n".join(lines)


QUALITY_WEIGHTS = {
    "positive_samples": 10, "negative_samples": 10, "scripted_generator": 10,
    "baseline_fp": 30, "metadata": 20, "shared_data_source": 20,
}


def _sample_counts():
    counts = {}
    for name in sorted(os.listdir(SAMPLES_DIR)):
        if name.endswith(".yml"):
            with open(os.path.join(SAMPLES_DIR, name), encoding="utf-8") as fh:
                doc = yaml.safe_load(fh) or {}
            counts[doc.get("rule")] = (len(doc.get("positive") or []), len(doc.get("negative") or []))
    return counts


def rule_quality():
    """Per-rule quality score (0-100) from evidence in the repo; every input is reproducible."""
    from scripts.validate_detections import BASELINE_COUNT, BASELINE_SEED, EXPECTED_RULE
    from simulator.benign_baseline import generate_baseline

    engine = SigmaEngine()
    baseline = generate_baseline(BASELINE_COUNT, BASELINE_SEED)
    fps = {r.id: 0 for r in engine.rules}
    for event in baseline:
        for rule in engine.match_all(event):
            fps[rule.id] += 1
    samples = _sample_counts()
    scripted = set(EXPECTED_RULE.values())
    sources = data_sources()
    rows = []
    for rule in engine.rules:
        soc_id = rule.soar.get("soc_rule_id", rule.id)
        pos, neg = samples.get(os.path.basename(rule.file), (0, 0))
        meta = [bool(rule.doc.get("falsepositives")), bool(rule.doc.get("references")),
                bool(rule.technique_ids), rule.level in {"low", "medium", "high", "critical"}]
        fp = fps[rule.id]
        parts = {
            "positive_samples": QUALITY_WEIGHTS["positive_samples"] if pos else 0,
            "negative_samples": QUALITY_WEIGHTS["negative_samples"] if neg else 0,
            "scripted_generator": QUALITY_WEIGHTS["scripted_generator"] if soc_id in scripted else 0,
            "baseline_fp": QUALITY_WEIGHTS["baseline_fp"] if fp == 0 else (QUALITY_WEIGHTS["baseline_fp"] // 2 if fp <= 5 else 0),
            "metadata": QUALITY_WEIGHTS["metadata"] * sum(meta) // len(meta),
            "shared_data_source": QUALITY_WEIGHTS["shared_data_source"] if len(sources[data_source_of(rule)]["rules"]) > 1 else 0,
        }
        rows.append({"rule": soc_id, "title": rule.title, "score": sum(parts.values()), "parts": parts,
                     "positives": pos, "negatives": neg, "baseline_fp": fp})
    return sorted(rows, key=lambda r: (r["score"], r["rule"]))


def render_quality():
    rows = rule_quality()
    lines = [
        "# Rule Quality Scores",
        "",
        "> Generated by `python scripts/coverage_report.py`. Scores are a heuristic built only",
        "> from evidence in this repo; they rank rules for review, they do not measure efficacy.",
        "",
        "| Component | Points | Earned when |",
        "| :--- | ---: | :--- |",
        f"| Positive samples | {QUALITY_WEIGHTS['positive_samples']} | `rules/tests/` has at least one event the rule must match |",
        f"| Negative samples | {QUALITY_WEIGHTS['negative_samples']} | `rules/tests/` has at least one near-miss the rule must ignore |",
        f"| Scripted generator | {QUALITY_WEIGHTS['scripted_generator']} | The attack simulator has a generator for the rule |",
        f"| Baseline FP risk | {QUALITY_WEIGHTS['baseline_fp']} | Full for 0 matches on the 600-event benign baseline, half for 1-5 |",
        f"| Metadata | {QUALITY_WEIGHTS['metadata']} | Falsepositives, references, ATT&CK tag, level (a quarter each) |",
        f"| Shared data source | {QUALITY_WEIGHTS['shared_data_source']} | Another rule uses the same telemetry, so collecting it is already justified |",
        "",
        "Lowest scores first.",
        "",
        "| Rule | Title | Score | Pos/Neg samples | Baseline FPs |",
        "| :--- | :--- | ---: | :---: | ---: |",
    ]
    lines += [f"| `{r['rule']}` | {r['title']} | {r['score']} | {r['positives']}/{r['negatives']} | {r['baseline_fp']} |" for r in rows]
    avg = sum(r["score"] for r in rows) / len(rows) if rows else 0
    lines += ["", f"Mean score: **{avg:.1f}** across {len(rows)} rules.", ""]
    return "\n".join(lines)


REPORTS = {"DATA_SOURCES.md": render_data_sources, "GAPS.md": render_gaps, "QUALITY.md": render_quality}


def main():
    parser = argparse.ArgumentParser(description="Generate coverage reports from the Sigma rules")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for name, render in REPORTS.items():
        path = os.path.join(OUT, name)
        body = render()
        if args.check:
            try:
                with open(path, encoding="utf-8") as fh:
                    if fh.read().replace("\r\n", "\n") != body:
                        stale.append(name)
            except FileNotFoundError:
                stale.append(name)
            continue
        os.makedirs(OUT, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(body)
        print(f"wrote docs/coverage/{name}")
    if args.check:
        for name in stale:
            print(f"stale: docs/coverage/{name}")
        sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
