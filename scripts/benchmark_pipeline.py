#!/usr/bin/env python3
"""
Reproducible in-process pipeline benchmark for the CyberPulse SOC Lab.

Runs every scripted attack generator N times through the SOAR pipeline (in
DRY_RUN mode, so no responder state changes) and prints per-stage latency
percentiles. These are lab measurements on emulated telemetry: detection runs
against synthetic events, enrichment reads a local cache, and responders are
simulated, so the numbers say nothing about production SOC latency.

Usage:
    python scripts/benchmark_pipeline.py [--runs 20] [--json]
    python scripts/benchmark_pipeline.py --runs 50 --histogram   # write docs/LATENCY_HISTOGRAM.md
"""

import argparse
import json
import os
import platform
import sys
from datetime import datetime, timezone

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from simulator.attack_simulator import SCRIPTED_GENERATORS  # noqa: E402
from soar.metrics_engine import calculate_percentile  # noqa: E402
from soar.soar_engine import SOAROrchestrator  # noqa: E402


HISTOGRAM_PATH = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "docs", "LATENCY_HISTOGRAM.md")
# Detection-latency bucket upper bounds in microseconds (last bucket is open-ended)
BUCKETS_US = [100, 250, 500, 1000, 2500]


def bucket_labels():
    labels, low = [], 0
    for high in BUCKETS_US:
        labels.append(f"{low}-{high}")
        low = high
    return labels + [f">={low}"]


def histogram(values_us):
    """Counts per bucket of BUCKETS_US for a list of microsecond values."""
    counts = [0] * (len(BUCKETS_US) + 1)
    for v in values_us:
        counts[next((i for i, high in enumerate(BUCKETS_US) if v < high), len(BUCKETS_US))] += 1
    return counts


def run_benchmark(runs):
    orchestrator = SOAROrchestrator(policy_mode="DRY_RUN")
    stages = {"detection_ms": [], "enrichment_ms": [], "containment_ms": [], "total_ms": []}
    by_technique = {}
    detected = 0
    attempted = 0

    for _ in range(runs):
        for _name, generator in SCRIPTED_GENERATORS:
            attempted += 1
            incident = orchestrator.process_event(generator())
            if not incident:
                continue
            detected += 1
            t = incident["pipeline_timing"]
            technique = incident["rule"].get("mitre_id", "Unknown")
            by_technique.setdefault(technique, []).append(t["stage1_detection_ms"] * 1000)
            stages["detection_ms"].append(t["stage1_detection_ms"])
            stages["enrichment_ms"].append(t["stage2_threat_intel_ms"])
            stages["containment_ms"].append(t["stage3_containment_ms"])
            stages["total_ms"].append(t["total_pipeline_latency_ms"])

    # Report microseconds: in-process stages are far below a millisecond.
    summary = {
        stage.replace("_ms", "_us"): {
            "p50": calculate_percentile([v * 1000 for v in values], 50),
            "p95": calculate_percentile([v * 1000 for v in values], 95),
            "max": round(max(values) * 1000, 2) if values else None,
        }
        for stage, values in stages.items()
    }
    return {
        "measured_at": datetime.now(timezone.utc).isoformat(),
        "basis": "Lab-measured, in-process, emulated telemetry, simulated responders (DRY_RUN)",
        "python": platform.python_version(),
        "platform": platform.platform(),
        "runs_per_generator": runs,
        "events_attempted": attempted,
        "events_detected": detected,
        "latency_us": summary,
        "detection_us_by_technique": by_technique,
    }


def render_histogram(result):
    labels = bucket_labels()
    lines = [
        "# Detection Latency per Technique",
        "",
        "> **Lab-measured, not reproducible to the microsecond.** Generated by",
        f"> `CYBERPULSE_LAB_MODE=true python scripts/benchmark_pipeline.py --runs {result['runs_per_generator']} --histogram`",
        f"> on {result['platform']}, Python {result['python']}, at {result['measured_at'][:19]}Z.",
        "> In-process Sigma evaluation of one synthetic event (stage 1 of the pipeline); no log",
        "> shipping, SIEM indexing or network time is included. Expect other numbers on other machines.",
        "",
        "Counts of runs per detection-latency bucket (microseconds).",
        "",
        "| Technique | Runs | p50 µs | p95 µs | " + " | ".join(labels) + " |",
        "| :--- | ---: | ---: | ---: | " + " | ".join(["---:"] * len(labels)) + " |",
    ]
    for technique, values in sorted(result["detection_us_by_technique"].items()):
        counts = histogram(values)
        lines.append(f"| {technique} | {len(values)} | {calculate_percentile(values, 50)} | "
                     f"{calculate_percentile(values, 95)} | " + " | ".join(str(c) for c in counts) + " |")
    lines.append("")
    return "\n".join(lines)


def main():
    from simulator.lab_guard import lab_mode_enabled
    if not lab_mode_enabled():
        sys.exit("Refusing to run: set CYBERPULSE_LAB_MODE=true (lab use only).")
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    parser.add_argument("--runs", type=int, default=20, help="runs per attack generator")
    parser.add_argument("--json", action="store_true", help="print raw JSON")
    parser.add_argument("--histogram", action="store_true", help=f"write {os.path.basename(HISTOGRAM_PATH)}")
    args = parser.parse_args()

    result = run_benchmark(args.runs)
    if args.histogram:
        with open(HISTOGRAM_PATH, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(render_histogram(result))
        print(f"wrote {HISTOGRAM_PATH}")
        return
    if args.json:
        print(json.dumps(result, indent=2))
        return

    print(f"CyberPulse lab pipeline benchmark ({result['basis']})")
    print(f"  {result['platform']} / Python {result['python']} / {result['measured_at']}")
    print(f"  events detected: {result['events_detected']}/{result['events_attempted']}")
    for stage, stats in result["latency_us"].items():
        print(f"  {stage:<15} p50={stats['p50']:>8} us   p95={stats['p95']:>8} us   max={stats['max']} us")


if __name__ == "__main__":
    main()
