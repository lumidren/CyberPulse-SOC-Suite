#!/usr/bin/env python3
"""
Replay the red vs blue scenario pack (roadmap F99) and write docs/SCENARIO_RESULTS.md.

    CYBERPULSE_LAB_MODE=true python scripts/run_scenarios.py                 # write the report
    CYBERPULSE_LAB_MODE=true python scripts/run_scenarios.py --check         # exit 1 if stale
    CYBERPULSE_LAB_MODE=true python scripts/run_scenarios.py --pack DIR --json   # someone else's pack

Exit status 2 means a step did not end as its scenario expects (a regression, or a fixed
bypass whose scenario needs updating).
"""

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from simulator.scenario_pack import DEFAULT_PACK, load_pack, run  # noqa: E402

REPORT = os.path.join(ROOT, "docs", "SCENARIO_RESULTS.md")


def results(pack=DEFAULT_PACK):
    return [run(s) for s in load_pack(pack)]


def render(runs):
    lines = ["# Red vs Blue Scenario Results", "",
             "> Generated by `CYBERPULSE_LAB_MODE=true python scripts/run_scenarios.py` from `scenarios/*.yml`.",
             "> Synthetic events replayed through the detection engine only; the same author wrote the",
             "> scenarios and the rules, so blue winning here is a regression check, not efficacy.", "",
             "| Scenario | Difficulty | Blue | Red | All steps as expected |", "| :--- | :--- | ---: | ---: | :--- |"]
    for r in runs:
        ok = all(s["as_expected"] for s in r["steps"])
        lines.append(f"| {r['id']}: {r['title']} | {r['difficulty']} | {r['blue']} | {r['red']} | {'yes' if ok else '**no**'} |")
    for r in runs:
        lines += ["", f"## {r['id']}: {r['title']}", "", "| Step | Technique | Expected | Outcome | Rules fired |",
                  "| :--- | :--- | :--- | :--- | :--- |"]
        for s in r["steps"]:
            mark = "" if s["as_expected"] else " (**unexpected**)"
            lines.append(f"| {s['id']} {s['name']} | {s['technique']} | {s['expected']} | {s['outcome']}{mark} | "
                         f"{', '.join(s['fired']) or '-'} |")
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Replay the red vs blue scenario pack")
    parser.add_argument("--pack", default=DEFAULT_PACK)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--json", action="store_true", help="print results as JSON instead of writing the report")
    args = parser.parse_args()
    runs = results(args.pack)
    unexpected = any(not s["as_expected"] for r in runs for s in r["steps"])
    if args.json:
        print(json.dumps(runs, indent=2))
    elif args.check:
        try:
            with open(REPORT, encoding="utf-8") as fh:
                stale = fh.read().replace("\r\n", "\n") != render(runs)
        except FileNotFoundError:
            stale = True
        if stale:
            sys.exit(1)
    else:
        with open(REPORT, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(render(runs))
        print(f"wrote {os.path.relpath(REPORT, ROOT)}")
    sys.exit(2 if unexpected else 0)


if __name__ == "__main__":
    main()
